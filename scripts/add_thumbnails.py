#!/usr/bin/env python3
"""
Add slide thumbnail images to the bioatlas.io atlas table.

Each image is matched to its slide by the Bio-Atlas slide number in the file
name ("3dpf_coronal_section-01_slide-1736.jpg"). The stage, plane and series
are looked up in site/assets/js/atlas-data.js, and the thumbnail is written to

    site/thumbs/<stage>/<plane>/<atlas>_<slide>.jpg

Afterwards site/assets/js/thumbs-available.js is regenerated. Series that have
thumbnails show them in the atlas table in place of the numbered buttons.

Usage (from the repository root):
    python3 scripts/add_thumbnails.py path/to/thumbnails/
    python3 scripts/add_thumbnails.py a.jpg b.png

Requires: pip install pillow
Runs on macOS, Windows and Linux.
"""
import argparse
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
THUMBS = SITE / "thumbs"
MAX_W, MAX_H = 480, 120          # thumbnails larger than this are reduced
EXTS = {".jpg", ".jpeg", ".png", ".tif", ".tiff", ".webp"}


def load_atlas_index():
    """slide number -> (stage id, plane, atlas id, position in series)"""
    js = (SITE / "assets/js/atlas-data.js").read_text()
    data = json.loads(js[js.index("{"):js.rindex("}") + 1])
    index = {}
    for age in data["ages"]:
        for plane, series in age["planes"].items():
            for slide in series["slides"]:
                index[slide["s"]] = (age["id"], plane, slide["atlas"], slide["n"])
    return index


def write_available():
    avail = {}
    for f in sorted(THUMBS.glob("*/*/*_*.jpg")):
        key = f.parent.parent.name + "/" + f.parent.name
        avail.setdefault(key, []).append(int(f.stem.split("_")[-1]))
    for k in avail:
        avail[k] = sorted(avail[k])
    out = SITE / "assets/js/thumbs-available.js"
    out.write_text(
        "// Generated by scripts/add_thumbnails.py. Do not edit by hand.\n"
        "// Slides (Bio-Atlas slide numbers) with thumbnails under site/thumbs/,\n"
        "// keyed by \"<stage>/<plane>\".\n"
        "const BIOATLAS_THUMBS = " + json.dumps(avail) + ";\n")
    return avail


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("inputs", nargs="+", help="image files or folders")
    args = ap.parse_args()

    files = []
    for p in map(Path, args.inputs):
        if p.is_dir():
            files += sorted(f for f in p.iterdir() if f.suffix.lower() in EXTS)
        elif p.is_file():
            files.append(p)
        else:
            sys.exit("Not found: " + str(p))

    index = load_atlas_index()
    done = 0
    for f in files:
        m = re.search(r"slide[-_ ]?(\d+)", f.stem, re.I)
        if not m:
            print("skip (no slide number in name):", f.name)
            continue
        s = int(m.group(1))
        if s not in index:
            print("skip (slide %d not in atlas-data.js): %s" % (s, f.name))
            continue
        stage, plane, atlas, n = index[s]
        im = Image.open(f).convert("RGB")
        im.thumbnail((MAX_W, MAX_H), Image.LANCZOS)
        dest = THUMBS / stage / plane / ("%s_%d.jpg" % (atlas, s))
        dest.parent.mkdir(parents=True, exist_ok=True)
        im.save(dest, "JPEG", quality=90, optimize=True)
        print("%s  ->  %s  (%s %s section %d, %dx%d)" % (
            f.name, dest.relative_to(ROOT).as_posix(), stage, plane, n, *im.size))
        done += 1

    avail = write_available()
    print("\n%d thumbnail(s) written. Series with thumbnails: %s" % (
        done, ", ".join("%s (%d)" % (k, len(v)) for k, v in avail.items()) or "none"))


if __name__ == "__main__":
    main()
