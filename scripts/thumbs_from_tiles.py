#!/usr/bin/env python3
"""
Make atlas-table thumbnails from the original Bio-Atlas tiles.

For every slide in site/assets/js/slides-index.js that has no thumbnail yet,
the smallest pyramid level that is still large enough is assembled from its
tiles and reduced to fit 480 x 120 px:

    site/thumbs/<stage>/<plane>/<atlas>_<slide>.jpg

Afterwards site/assets/js/thumbs-available.js is regenerated (same format as
scripts/add_thumbnails.py). Existing thumbnails are kept; use --force to redo.

Usage (from the repository root):
    python scripts/thumbs_from_tiles.py E:\\LegacyBioAtlas_Histology\\bioatlas_fullres

Requires: pip install pillow
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
THUMBS = SITE / "thumbs"
MAX_W, MAX_H = 480, 120


def load_js(name):
    js = (SITE / "assets/js" / name).read_text(encoding="utf-8")
    return json.loads(js[js.index("{"):js.rindex("}") + 1])


def ceil_div(a, b):
    return -(-a // b)


def level_image(tiles_dir, info, lev):
    w, h, tw, th, levels, single = info
    lw, lh = ceil_div(w, 2 ** lev), ceil_div(h, 2 ** lev)
    d = os.path.join(tiles_dir, str(lev))
    if lev >= single:
        return Image.open(os.path.join(d, "0.jpg")).convert("RGB")
    cols, rows = ceil_div(lw, tw), ceil_div(lh, th)
    canvas = Image.new("RGB", (lw, lh), (255, 255, 255))
    for t in range(cols * rows):
        p = os.path.join(d, "%d.jpg" % t)
        if os.path.exists(p):
            canvas.paste(Image.open(p).convert("RGB"), ((t % cols) * tw, (t // cols) * th))
    return canvas


def write_available():
    avail = {}
    for f in sorted(THUMBS.glob("*/*/*_*.jpg")):
        key = f.parent.parent.name + "/" + f.parent.name
        avail.setdefault(key, []).append(int(f.stem.split("_")[-1]))
    for k in avail:
        avail[k] = sorted(avail[k])
    (SITE / "assets/js/thumbs-available.js").write_text(
        "// Generated by scripts/add_thumbnails.py or scripts/thumbs_from_tiles.py. Do not edit by hand.\n"
        "// Slides (Bio-Atlas slide numbers) with thumbnails under site/thumbs/,\n"
        "// keyed by \"<stage>/<plane>\".\n"
        "const BIOATLAS_THUMBS = " + json.dumps(avail) + ";\n")
    return avail


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("extract", help="output folder of bioatlas_extract.py (contains tiles/)")
    ap.add_argument("--force", action="store_true", help="redo existing thumbnails")
    ap.add_argument("--time-limit", type=float, default=0, help="stop after this many seconds (re-run to continue)")
    args = ap.parse_args()
    tiles = Path(args.extract) / "tiles"
    if not tiles.is_dir():
        sys.exit("Not found: %s" % tiles)

    slides = load_js("slides-index.js")
    atlas = {}
    for age in load_js("atlas-data.js")["ages"]:
        for plane, series in age["planes"].items():
            for s in series["slides"]:
                atlas[s["s"]] = (age["id"], plane, s["atlas"])

    t0 = time.time(); done = 0; left = 0
    for key in sorted(slides, key=int):
        s = int(key)
        if s not in atlas:
            continue
        stage, plane, aid = atlas[s]
        dest = THUMBS / stage / plane / ("%s_%d.jpg" % (aid, s))
        if dest.exists() and not args.force:
            continue
        if args.time_limit and time.time() - t0 > args.time_limit:
            left += 1
            continue
        info = slides[key]
        w, h, levels = info[0], info[1], info[4]
        # smallest level that still covers the thumbnail box in at least one direction
        lev = 0
        for cand in range(levels - 1, -1, -1):
            if ceil_div(w, 2 ** cand) >= MAX_W or ceil_div(h, 2 ** cand) >= MAX_H:
                lev = cand
                break
        im = level_image(str(tiles / ("%010d" % s)), info, lev)
        im.thumbnail((MAX_W, MAX_H), Image.LANCZOS)
        dest.parent.mkdir(parents=True, exist_ok=True)
        im.save(dest, "JPEG", quality=88, optimize=True)
        done += 1

    avail = write_available()
    print("%d thumbnail(s) written, %d remaining. %d slides in %d series now have thumbnails." % (
        done, left, sum(len(v) for v in avail.values()), len(avail)))


if __name__ == "__main__":
    main()
