#!/usr/bin/env python3
"""
Convert Bio-Atlas slide TIFFs into Deep Zoom (DZI) tiles for the bioatlas.io
slide viewer (OpenSeadragon), and update the list of slides that have tiles.

Each slide is identified by its Bio-Atlas slide number, read from the file
name ("..._slide-1736.tif") or from the TIFF description ("Bio-Atlas slide
1736 | ..."). The stage, plane and series are looked up in
site/assets/js/atlas-data.js, and the tiles are written where the viewer
expects them:

    site/tiles/<stage>/<plane>/<atlas>_<slide>.dzi
    site/tiles/<stage>/<plane>/<atlas>_<slide>_files/<level>/<col>_<row>.jpeg

Afterwards site/assets/js/tiles-available.js is regenerated, so the atlas
table opens these slides in the bioatlas.io viewer; slides without tiles keep
opening the Penn State viewer.

Usage (from the repository root):
    python3 scripts/tiff_to_dzi.py path/to/slides/          # a folder of .tif files
    python3 scripts/tiff_to_dzi.py a.tif b.tif --force      # re-tile existing slides

Requires: pip install tifffile imagecodecs pillow numpy
Runs on macOS, Windows and Linux.
"""
import argparse
import json
import math
import re
import sys
from pathlib import Path

import numpy as np
import tifffile
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
TILES = SITE / "tiles"
TILE, OVERLAP, QUALITY = 254, 1, 88          # same layout as scripts/download_slides.py

Image.MAX_IMAGE_PIXELS = None                 # whole-slide images are large by design


def load_atlas_index():
    """slide number -> (stage id, plane, atlas id, position in series)"""
    js = (SITE / "assets/js/atlas-data.js").read_text()
    data = json.loads(js[js.index("{"):js.rindex("}") + 1])
    index = {}
    for age in data["ages"]:
        for plane, series in age["planes"].items():
            for slide in series["slides"]:
                index[slide["s"]] = (age["id"], plane, slide["atlas"], slide["n"])
    return index


def slide_number(path, tif):
    m = re.search(r"slide[-_ ]?(\d+)", path.stem, re.I)
    if m:
        return int(m.group(1))
    desc = tif.pages[0].description or ""
    m = re.search(r"Bio-Atlas slide (\d+)", desc)
    return int(m.group(1)) if m else None


def to_rgb(arr):
    if arr.ndim == 2:
        arr = np.stack([arr] * 3, axis=-1)
    if arr.shape[-1] == 4:
        arr = arr[..., :3]
    if arr.dtype != np.uint8:                 # e.g. 16-bit scans
        lo, hi = np.percentile(arr, (0.1, 99.9))
        arr = np.clip((arr.astype(np.float32) - lo) / max(hi - lo, 1) * 255, 0, 255).astype(np.uint8)
    return arr


def write_dzi(img, base):
    """Write base.dzi and base_files/ for a PIL RGB image."""
    w, h = img.size
    max_level = math.ceil(math.log2(max(w, h)))
    files = base.parent / (base.name + "_files")
    level_img = img
    for level in range(max_level, -1, -1):
        lw, lh = level_img.size
        d = files / str(level)
        d.mkdir(parents=True, exist_ok=True)
        for col in range(math.ceil(lw / TILE)):
            for row in range(math.ceil(lh / TILE)):
                x0 = col * TILE - (OVERLAP if col else 0)
                y0 = row * TILE - (OVERLAP if row else 0)
                x1 = min((col + 1) * TILE + OVERLAP, lw)
                y1 = min((row + 1) * TILE + OVERLAP, lh)
                level_img.crop((x0, y0, x1, y1)).save(d / f"{col}_{row}.jpeg", quality=QUALITY)
        if level:
            level_img = level_img.resize((max(1, math.ceil(lw / 2)), max(1, math.ceil(lh / 2))), Image.LANCZOS)
    base.with_suffix(".dzi").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<Image xmlns="http://schemas.microsoft.com/deepzoom/2008" Format="jpeg" '
        f'Overlap="{OVERLAP}" TileSize="{TILE}">\n'
        f'  <Size Width="{w}" Height="{h}"/>\n</Image>\n')


def write_available():
    """Regenerate the list the atlas table uses to choose the local viewer."""
    avail = {}
    for dzi in sorted(TILES.glob("*/*/*.dzi")):
        stage, plane = dzi.parent.parent.name, dzi.parent.name
        s = int(dzi.stem.split("_")[-1])
        avail.setdefault(f"{stage}/{plane}", []).append(s)
    out = SITE / "assets/js/tiles-available.js"
    out.write_text(
        "// Generated by scripts/tiff_to_dzi.py. Do not edit by hand.\n"
        "// Slides (Bio-Atlas slide numbers) with Deep Zoom tiles under site/tiles/,\n"
        "// keyed by \"<stage>/<plane>\". The atlas opens these in /viewer/.\n"
        "const BIOATLAS_TILES = " + json.dumps(avail, indent=1) + ";\n")
    return sum(len(v) for v in avail.values())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inputs", nargs="+", help="TIFF files and/or folders of TIFFs")
    ap.add_argument("--force", action="store_true", help="re-tile slides that already have tiles")
    args = ap.parse_args()

    files = []
    for p in map(Path, args.inputs):
        files += sorted(p.glob("*.tif*")) if p.is_dir() else [p]
    index = load_atlas_index()
    done = skipped = 0
    for f in files:
        with tifffile.TiffFile(f) as tif:
            s = slide_number(f, tif)
            if s is None or s not in index:
                print(f"skip {f.name}: slide number {s} not found in the atlas data")
                skipped += 1
                continue
            stage, plane, atlas, n = index[s]
            base = TILES / stage / plane / f"{atlas}_{s}"
            if base.with_suffix(".dzi").exists() and not args.force:
                print(f"have {stage} {plane} #{n:02d} (slide {s}); use --force to redo")
                continue
            arr = to_rgb(tif.pages[0].asarray())        # page 0 = full resolution
        img = Image.fromarray(arr)
        write_dzi(img, base)
        print(f"tiled {stage} {plane} #{n:02d} (slide {s}): {img.size[0]} x {img.size[1]} px")
        done += 1
    total = write_available()
    print(f"\n{done} slide(s) tiled, {skipped} skipped. {total} slide(s) now have tiles.")


if __name__ == "__main__":
    main()
